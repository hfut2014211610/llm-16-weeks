import torch, torch.nn.functional as F, math
torch.manual_seed(0)
print("== L1 softmax")
logits = torch.tensor([2.0, 1.0, 0.1])
e = torch.exp(logits); print(e, e.sum()); print(e/e.sum()); print(F.softmax(logits, dim=-1))
print("== L1 sample")
p = torch.tensor([0.659, 0.242, 0.099]); print(torch.multinomial(p, 10, replacement=True))
print("== L2 matmul")
x = torch.tensor([1.0, 2.0]); W = torch.tensor([[1.0, 0.0, -1.0],[0.5, 2.0, 1.0]])
print(x @ W)
print(torch.randn(32,64,64).shape, (torch.randn(32,64,64) @ torch.randn(64,65)).shape)
print("== L3 embedding")
emb = torch.nn.Embedding(5, 3); print(emb.weight.data); print(emb(torch.tensor([2, 0])))
oh = F.one_hot(torch.tensor(2), 5).float(); print(oh @ emb.weight.data)
print("== L4 dot")
a=torch.tensor([1.,2.]); b=torch.tensor([2.,4.]); c=torch.tensor([-2.,1.]); print(a@b, a@c)
print("== L4 weighted avg")
w=torch.tensor([0.7,0.2,0.1]); v=torch.tensor([[10.],[20.],[30.]]); print(w@v)
print("== L5 mask")
T=4; s=torch.zeros(T,T); tril=torch.tril(torch.ones(T,T)); print(tril)
s=s.masked_fill(tril==0, float('-inf')); print(s); print(F.softmax(s,dim=-1))
print("== L5 sqrt d")
for d in [4,64,1024]:
    q=torch.randn(10000,d); k=torch.randn(10000,d); print(d, (q*k).sum(-1).std().item(), ((q*k).sum(-1)/math.sqrt(d)).std().item())
print(F.softmax(torch.tensor([30.,20.,10.]),-1), F.softmax(torch.tensor([3.,2.,1.]),-1))
print("== L6 layernorm")
h=torch.tensor([2.,4.,6.,8.]); m=h.mean(); var=((h-m)**2).mean(); print(m,var,(h-m)/torch.sqrt(var+1e-5)); print(F.layer_norm(h,(4,)))
print(F.relu(torch.tensor([-2.,0.,3.])))
print("== L7 CE")
p=F.softmax(torch.tensor([2.0,1.0,0.1]),-1); print(-torch.log(p)); print(F.cross_entropy(torch.tensor([[2.0,1.0,0.1]]), torch.tensor([0])))
print(-math.log(1/65))
print("== L8 grad descent")
w=torch.tensor(5.0, requires_grad=True)
for i in range(5):
    loss=(w-2)**2; loss.backward()
    print(i, round(w.item(),4), round(loss.item(),4), round(w.grad.item(),4))
    with torch.no_grad(): w-=0.1*w.grad
    w.grad=None
